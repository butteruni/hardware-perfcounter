"""Generate A7xx/A8xx APIs from pinned Mesa definitions and KGSL group IDs.

Mesa's group order, register addresses, and slot counts are NOT KGSL group IDs.
No product masks or formulas are inferred from event names.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/adreno"


def events(family):
    groups = json.loads((SOURCE / "kgsl_groups.json").read_text())["groups"]
    enums = {e.get("name"): e for e in ET.parse(SOURCE / f"{family}_perfcntrs.xml").getroot()
             if e.tag.endswith("enum")}
    layout = json.loads((SOURCE / f"{family}_perfcntrs.json").read_text())
    result = []
    for group in layout["groups"]:
        name = group["name"]
        if name not in groups:
            raise ValueError(f"No KGSL mapping for Mesa group {name}")
        for value in enums[group["countable_type"]]:
            if not value.tag.endswith("value"):
                continue
            event = value.attrib["name"].removeprefix(family.upper() + "_")
            if "RESERVED" in event or "NOT_USED" in event:
                continue
            selector = int(value.attrib["value"], 0)
            if not 0 <= selector < 65536:
                raise ValueError("Selector exceeds the modern enum encoding")
            symbol = f"HPC_GPU_ADRENO_{family.upper()}_" + ("BV_" if name.startswith("BV_") else "") + event
            result.append((symbol, groups[name], selector))
    if len({r[0] for r in result}) != len(result) or len({r[1:] for r in result}) != len(result):
        raise ValueError("Duplicate event name or KGSL selection")
    return result


def generate(family):
    rows = events(family)
    prefix = f"hpc_gpu_adreno_{family}"
    notice = ("/* Generated by scripts/generate_modern_adreno.py.\n"
              " * Event definitions: Mesa/Freedreno, MIT. See third_party/adreno.\n"
              " * API implementation: SPDX-License-Identifier: Apache-2.0 */\n")
    header = notice + f'''#ifndef HPC_GPU_ADRENO_{family.upper()}_H_
#define HPC_GPU_ADRENO_{family.upper()}_H_
#include "hpc/gpu/adreno/raw.h"
#ifdef __cplusplus
extern "C" {{
#endif

/* Static family candidates, not per-product availability. Query KGSL slots and
 * validate event semantics on the device. Enum encoding uses 16 selector bits;
 * unlike the legacy A5/A6 enum, group = value >> 16. */
typedef enum {prefix}_counter_e {{
'''
    header += "\n".join(f"  {name} = 0x{(group << 16) | selector:08x}," for name, group, selector in rows)
    header += f'''
}} {prefix}_counter_t;

/* The raw context API supplies start/query/stop/destroy. Creation checks the
 * chip family and enum membership; it does not allocate GPU slots until start.
 * A702/A704's different A7v event layout is not claimed by the A7xx enum API. */
int {prefix}_create_context(uint32_t count,
    const {prefix}_counter_t *counters,
    const hpc_gpu_host_allocation_callbacks_t *allocator,
    hpc_gpu_adreno_raw_context_t **out_context);
#ifdef __cplusplus
}}
#endif
#endif
'''
    source = notice + f'''#include "hpc/gpu/adreno/{family}.h"
#include <errno.h>

static int valid_counter(uint32_t counter) {{
  switch (counter) {{
'''
    source += "\n".join(f"    case {name}:" for name, _, _ in rows)
    source += '''      return 1;
    default: return 0;
  }
}
'''
    source += f'''
int {prefix}_create_context(uint32_t count,
    const {prefix}_counter_t *counters,
    const hpc_gpu_host_allocation_callbacks_t *allocator,
    hpc_gpu_adreno_raw_context_t **out_context) {{
  if (!out_context) return -EINVAL;
  *out_context = NULL;
  if (!count || count > 4096 || !counters || !allocator ||
      !allocator->alloc || !allocator->free) return -EINVAL;
  for (uint32_t i = 0; i < count; ++i)
    if (!valid_counter((uint32_t)counters[i])) return -EINVAL;
  hpc_gpu_adreno_kgsl_counter_t *raw = allocator->alloc(
      allocator->user_data, count * sizeof(*raw));
  if (!raw) return -ENOMEM;
  for (uint32_t i = 0; i < count; ++i) {{
    raw[i].group_id = (uint32_t)counters[i] >> 16;
    raw[i].countable_selector = (uint32_t)counters[i] & 65535u;
    raw[i].value = 0;
  }}
  int error = hpc_gpu_adreno_raw_create_context(count, raw, allocator, out_context);
  allocator->free(allocator->user_data, raw);
  if (error) return error;
  hpc_gpu_adreno_kgsl_device_info_t info;
  hpc_gpu_adreno_raw_get_device_info(*out_context, &info);
  uint32_t chip = info.chip_id & 0xffffff00u;
  if ((info.chip_id >> 24) != {family[1]} ||
      chip == 0x07000200u || chip == 0x07000400u) {{
    hpc_gpu_adreno_raw_destroy_context(*out_context);
    *out_context = NULL;
    return -HPC_GPU_ERROR_INCOMPATIBLE_DEVICE;
  }}
  return 0;
}}
'''
    return {ROOT / f"include/hpc/gpu/adreno/{family}.h": header,
            ROOT / f"lib/gpu/adreno/{family}.c": source}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for record in json.loads((SOURCE / "sources.json").read_text()):
        if hashlib.sha256((SOURCE / record["file"]).read_bytes()).hexdigest() != record["sha256"]:
            raise SystemExit("Pinned source changed: " + record["file"])
    for family in ("a7xx", "a8xx"):
        for path, text in generate(family).items():
            if args.check:
                if path.read_text() != text:
                    raise SystemExit("Stale generated file: " + str(path))
            else:
                path.write_text(text, newline="\n")
        print(f"{family}: {len(events(family))} named KGSL candidates")


if __name__ == "__main__":
    main()
